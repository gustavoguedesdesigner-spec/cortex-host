export const suppliers: Supplier[] = supplierDefinitions.map((s) => ({
  ...s,
  scoreGeral: calcularScoreGeral(s.scoreBreakdown, s.pesos, s.penalidades),
}))

export function getSupplierById(id: string): Supplier | undefined {
  return suppliers.find((s) => s.id === id)
}

export function getSuppliersByCategory(categoria: string): Supplier[] {
  return suppliers.filter((s) => s.categoriasIds.includes(categoria as Supplier['categoriaPrincipalId']))
}

export function getSuppliersByOperationalStatus(status: Supplier['statusOperacional']): Supplier[] {
  return suppliers.filter((s) => s.statusOperacional === status)
}

export function getSuppliersWithOpenDivergences(): Supplier[] {
  return suppliers.filter((s) => s.divergenciasAbertas > 0)
}

export function getTotalCompradoAmostra(): number {
  return suppliers.reduce((sum, s) => sum + s.valorCompradoPeriodo, 0)
}

/** Resolve o id do fornecedor a partir do nome — usado pelas conexões com Unidades e Central de Operações. */
export function getSupplierIdByName(nome: string): string | undefined {
  return suppliers.find((s) => s.nome === nome)?.id
}
