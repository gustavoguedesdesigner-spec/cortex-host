export function getUserById(id: string): User | undefined {
  return users.find((u) => u.id === id)
}

export function getUsersByUnit(unitId: string): User[] {
  return users.filter((u) => u.unidades.includes('*') || u.unidades.includes(unitId))
}

export function getUsersByRole(roleId: string): User[] {
  return users.filter((u) => u.roleId === roleId)
}

export function getUnitDisplayName(user: User): string {
  if (user.unidades.includes('*')) return 'Todas as unidades'
  return `${user.unidades.length} unidade${user.unidades.length > 1 ? 's' : ''}`
}

